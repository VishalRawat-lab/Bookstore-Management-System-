CREATE TABLE customers (
 customer_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 customer_name VARCHAR2(100) NOT NULL,
 email VARCHAR2(150) UNIQUE NOT NULL,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);
CREATE TABLE books (
 book_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 title VARCHAR2(160) NOT NULL, author VARCHAR2(100) NOT NULL,
 category VARCHAR2(60) NOT NULL, price NUMBER(10,2) NOT NULL CHECK(price >= 0),
 stock_qty NUMBER DEFAULT 0 NOT NULL CHECK(stock_qty >= 0),
 reorder_level NUMBER DEFAULT 5 NOT NULL CHECK(reorder_level >= 0),
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);
CREATE TABLE wallet_accounts (
 account_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 customer_id NUMBER NOT NULL REFERENCES customers(customer_id),
 balance NUMBER(12,2) DEFAULT 0 NOT NULL CHECK(balance >= 0),
 account_status VARCHAR2(12) DEFAULT 'ACTIVE' CHECK(account_status IN ('ACTIVE','BLOCKED')),
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);
CREATE TABLE book_orders (
 order_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 customer_id NUMBER NOT NULL REFERENCES customers(customer_id),
 order_date TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
 subtotal NUMBER(12,2) NOT NULL, discount_amount NUMBER(12,2) DEFAULT 0 NOT NULL,
 total_amount NUMBER(12,2) NOT NULL,
 order_status VARCHAR2(20) DEFAULT 'PLACED' CHECK(order_status IN ('PLACED','PROCESSING','SHIPPED','CANCELLED'))
);
CREATE TABLE order_items (
 order_item_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 order_id NUMBER NOT NULL REFERENCES book_orders(order_id),
 book_id NUMBER NOT NULL REFERENCES books(book_id),
 quantity NUMBER NOT NULL CHECK(quantity > 0),
 unit_price NUMBER(10,2) NOT NULL, line_total NUMBER(12,2) NOT NULL
);
CREATE TABLE account_audit (
 audit_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 account_id NUMBER NOT NULL, old_balance NUMBER(12,2), new_balance NUMBER(12,2),
 changed_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
 changed_by VARCHAR2(128) DEFAULT USER, action_note VARCHAR2(250)
);
CREATE TABLE fund_transfers (
 transfer_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 from_account NUMBER NOT NULL REFERENCES wallet_accounts(account_id),
 to_account NUMBER NOT NULL REFERENCES wallet_accounts(account_id),
 amount NUMBER(12,2) NOT NULL CHECK(amount > 0),
 transfer_time TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL, transfer_status VARCHAR2(20) NOT NULL
);
